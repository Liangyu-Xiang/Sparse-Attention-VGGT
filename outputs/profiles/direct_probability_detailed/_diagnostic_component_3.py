def _diagnostic_component_3(OUT, PRIOR, Z, MEM, DIST, DR, QUAL, REMOVE, AMOUNT, ALLOW, POP, CLUSTERS, ERROR, COST, OBJECTIVE, OWNER, N: tl.constexpr, F: tl.constexpr, D: tl.constexpr, W: tl.constexpr, COUNT, C: tl.constexpr, M: tl.constexpr, BD: tl.constexpr, COUNT_PTR: tl.constexpr):
    if COUNT_PTR:
        COUNT = tl.load(COUNT)
    g = tl.program_id(0)
    ci = tl.program_id(1) * C + tl.arange(0, C)
    m = tl.arange(0, M)
    j = tl.arange(0, M)
    d = tl.arange(0, BD)
    c = tl.load(CLUSTERS + ci, ci < COUNT, 0)
    member = tl.load(MEM + c[:, None] * W + m[None, :], ci[:, None] < COUNT, -1)
    valid = (ci[:, None] < COUNT) & (member >= 0)
    weight = tl.load(PRIOR + g * N + tl.maximum(member, 0), valid, 0.0)
    repdist = tl.load(DR + tl.maximum(member, 0), valid, 0.0)
    rep = tl.sum(weight * repdist, 1)
    values = tl.load(Z + tl.maximum(member, 0)[:, :, None] * D + d[None, None, :], valid[:, :, None] & (d[None, None, :] < D), 0.0)
    moment = tl.sum(weight[:, :, None] * values, 1)
    drop = tl.sqrt(tl.sum(moment * moment, 1))
    candidates = tl.load(MEM + c[:, None] * W + j[None, :], ci[:, None] < COUNT, -1)
    qualified = tl.load(QUAL + g * N + tl.maximum(candidates, 0), (ci[:, None] < COUNT) & (candidates >= 0), False)
    distance = tl.load(DIST + tl.maximum(member, 0)[:, :, None] * W + j[None, None, :], valid[:, :, None], float('inf'))
    distance = tl.where(qualified[:, None, :], distance, float('inf'))
    minimum = tl.min(distance, 2)
    owner = tl.min(tl.where(qualified[:, None, :] & (distance == minimum[:, :, None]), candidates[:, None, :], 2147483647), 2)
    own = tl.load(QUAL + g * N + tl.maximum(member, 0), valid, False)
    owner = tl.where(own, member, owner)
    has = valid & (owner < 2147483647)
    hist = tl.sum(tl.where(has, weight * minimum, 0.0), 1)
    remove = tl.load(REMOVE + g * F + c, ci < COUNT, False)
    amount = tl.load(AMOUNT + g * F + c, ci < COUNT, 0)
    allowed = tl.load(ALLOW + g * F + c, ci < COUNT, False)
    pop = tl.load(POP + c, ci < COUNT, 0.0)
    rep_error = tl.where(remove, float('inf'), rep)
    hist_error = tl.where(amount > 0, hist, float('inf'))
    exact = tl.where(allowed, 0.0, float('inf'))
    base = (g * F + c) * 4
    tl.store(OUT + g * F + c, tl.sum(tl.where(has, owner, 0).to(tl.float32), 1), ci < COUNT)